import Foundation

/// 画面に出る指標の定義文。
///
/// 同じ指標が複数の画面に出るため文言を1か所にまとめている。
/// 定義が分からない数字は、良くなったのか悪くなったのかを判断できず、
/// かえって学習の妨げになるため、すべての指標に説明を用意する方針にしている。
enum MetricExplanations {
    static let todayAccuracy = """
    今日解答した問題のうち、正解した割合です。4択クイズとタイピングの両方を合算しています。

    同じ単語を複数回解いた場合は、その回数分すべてを数えます。
    """

    static let todayStudied = """
    今日解答した問題数です。4択クイズとタイピングの両方を合算し、同じ単語を複数回解いた場合はその都度数えます。
    """

    static let overallAccuracy = """
    これまでの全解答のうち、正解した割合です。出題されたことのある単語だけを対象にしています。

    復習で解き直した分も含むため、苦手な単語を繰り返すと一時的に下がることがあります。
    """

    static let mastery = """
    単語ごとの習熟段階です。直近の正誤ではなく、間隔をあけて思い出せたかどうかで判定します。

    ・未学習 … まだ一度も出題されていない
    ・要復習 … 直近で間違えた、または復習期限が来ている
    ・学習中 … 正解を重ねている途中（1〜3日間隔で再出題）
    ・覚えた … 1週間以上あけても正解できた

    正解するたびに復習の間隔が 1日 → 3日 → 7日 → 14日 → 30日 と伸び、間違えると最短に戻ります。
    「覚えた」は7日以上の間隔に到達した単語です。直前に1回正解しただけでは「学習中」までで、
    翌日には忘れている単語を覚えた扱いにしないようにしています。
    """

    static let dueForReview = """
    復習の期限が来ている単語の数です。間違えた単語はその日のうちに、
    正解した単語は習熟段階に応じた日数をあけて、再び出題対象になります。
    """

    static let streak = """
    連続して学習した日数です。1問でも解答した日を「学習した日」として数えます。

    今日まだ解答していなくても、前日までの記録は途切れたことにしません。
    """
}
